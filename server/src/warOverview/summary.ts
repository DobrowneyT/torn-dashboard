// The War Overview summary, server side (#811).
//
// ⚠️ **This is a SECOND implementation of `frontend/src/utils/warOverviewSummary.js`,
// and that is a deliberate, uncomfortable choice.** The page must compute
// locally — the summary re-renders on every drag of the range slider, and a
// round trip per drag would be unusable. The bot cannot run browser JS. So the
// numbers get computed twice, in two languages' worth of distance.
//
// ⚠️ What makes that survivable is `test/war-overview-parity.test.ts`, which
// runs BOTH implementations over the same fixtures and fails when they
// disagree. Drift becomes a red build instead of a Discord embed quietly
// contradicting the page it claims to mirror. Do not edit this file without
// running that test — and if you change behaviour, change the frontend in the
// same commit.
//
// This repo has watched one idea drift across two implementations three times
// in two days: `LOSS_RESULTS` in two files, `classifyEventType` local to the
// view while the summary silently stopped describing the graph, and
// `WIN_RESULTS` disagreeing about `Special`.

/** Win results that SCORE. ⚠️ `Special` is excluded — see the note below. */
const WIN_RESULTS = new Set(['Attacked', 'Mugged', 'Hospitalized', 'Arrested', 'Looted'])

/**
 * ⚠️ `Special` counts as an attack for DISPLAY but is absent from the payout
 * set, because every payout path tests that set directly. Mirrors the frontend
 * `TIMELINE_WIN_RESULTS`.
 */
const TIMELINE_WIN_RESULTS = new Set([...WIN_RESULTS, 'Special'])

const LOSS_RESULTS = new Set(['Lost', 'Timeout', 'Interrupted', 'Stalemate', 'Escape'])
const ASSIST_RESULT = 'Assist'

export const NO_FACTION_ID = 0
export const factionKey = (fid: unknown): number => Number(fid) || NO_FACTION_ID

export const REVIVE_FAILURE = 'failure'
export const reviveOutcome = (r: { result?: string | null }): 'success' | 'failure' =>
  String(r?.result ?? '').toLowerCase() === REVIVE_FAILURE ? 'failure' : 'success'

export type EventType = 'attack' | 'assist' | 'loss' | null

export function classifyEventType(result?: string | null): EventType {
  if (!result) return null
  if (result === ASSIST_RESULT) return 'assist'
  if (TIMELINE_WIN_RESULTS.has(result)) return 'attack'
  if (LOSS_RESULTS.has(result)) return 'loss'
  return null
}

export interface Bucket { attack: number; assist: number; loss: number; total: number }
export interface ReviveStats { success: number; failure: number; total: number }
export interface Summary {
  fromTs: number; toTs: number
  outgoing: Bucket; incoming: Bucket; revives: ReviveStats
}

const emptyBucket = (): Bucket => ({ attack: 0, assist: 0, loss: 0, total: 0 })

export interface SummariseArgs {
  attacks?: any[]
  revives?: any[]
  fromTs: number
  toTs: number
  ourFactionId: number
  /** null means "all factions". */
  selectedFactionIds?: Set<number> | null
  mode?: 'faction' | 'member'
  memberId?: number | null
}

/**
 * Count what the plot would show for this window and selection.
 *
 * ⚠️ `total` counts every attack in scope including results this classifier
 * does not recognise, so the three named columns can sum to LESS. A result type
 * Torn adds later shows as a gap rather than being filed under "loss".
 */
export function summariseWindow({
  attacks = [], revives = [], fromTs, toTs,
  ourFactionId, selectedFactionIds = null, mode = 'faction', memberId = null,
}: SummariseArgs): Summary {
  const inWindow = (ts: number) => ts >= fromTs && ts <= toTs
  // ⚠️ Through `factionKey`, so a null faction tests as 0 — the id the
  // "(no faction)" checkbox uses. Comparing the raw value makes it inert.
  const picked = (fid: unknown) =>
    selectedFactionIds == null || selectedFactionIds.has(factionKey(fid))

  const outgoing = emptyBucket()
  const incoming = emptyBucket()

  for (const a of attacks) {
    if (!inWindow(Number(a.started))) continue
    const type = classifyEventType(a.result)

    const isOurs = mode === 'member'
      ? Number(a.attacker_id) === Number(memberId)
      : Number(a.attacker_faction_id) === Number(ourFactionId)
    // ⚠️ The OTHER side decides whether this event is on the graph. Testing our
    // own faction would make the filter a no-op for outgoing rows.
    if (isOurs && picked(a.defender_faction_id)) {
      outgoing.total += 1
      if (type) outgoing[type] += 1
    }

    const isAgainstUs = mode === 'member'
      ? Number(a.defender_id) === Number(memberId)
      : Number(a.defender_faction_id) === Number(ourFactionId)
    if (isAgainstUs && picked(a.attacker_faction_id)) {
      incoming.total += 1
      if (type) incoming[type] += 1
    }
  }

  // ⚠️ No `picked()` here, on purpose. Being revived by a stranger is not
  // something you choose, and the reviver is almost never the faction you are
  // warring — faction-filtering revives is what emptied the page's revive panel.
  const revStats: ReviveStats = { success: 0, failure: 0, total: 0 }
  for (const r of revives) {
    if (!inWindow(Number(r.timestamp))) continue
    const mine = mode === 'member'
      ? Number(r.target_id) === Number(memberId)
      : Number(r.target_faction_id) === Number(ourFactionId)
    if (!mine) continue
    revStats[reviveOutcome(r)] += 1
    revStats.total += 1
  }

  return { fromTs, toTs, outgoing, incoming, revives: revStats }
}
