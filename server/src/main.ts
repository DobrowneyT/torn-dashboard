// Entry point for one per-faction API process. All per-faction identity comes
// from the environment (set by docker compose), never from code.
import pg from 'pg'
import { buildServer } from './app.js'

const factionSlug = process.env.FACTION_SLUG
if (!factionSlug) {
  console.error('FACTION_SLUG is required')
  process.exit(1)
}

const port = Number(process.env.PORT ?? 8080)
if (!Number.isInteger(port) || port < 1 || port > 65535) {
  console.error(`PORT must be a valid port number, got "${process.env.PORT}"`)
  process.exit(1)
}
const databaseUrl = process.env.DATABASE_URL
const jwtSecret = process.env.JWT_SECRET
const tornBaseUrl = process.env.TORN_API_BASE ?? 'https://api.torn.com'
const keyEncryptionKey = process.env.KEY_ENCRYPTION_KEY || undefined

// VAPID keypair for Web Push (#207). Operator step — generate with
// `npx web-push generate-vapid-keys` (see docs/PUSH.md). All three must be set
// for push to arm; otherwise the endpoints still exist but delivery is a no-op.
const vapid =
  process.env.VAPID_PUBLIC_KEY && process.env.VAPID_PRIVATE_KEY
    ? {
        publicKey: process.env.VAPID_PUBLIC_KEY,
        privateKey: process.env.VAPID_PRIVATE_KEY,
        subject: process.env.VAPID_SUBJECT || 'mailto:admin@example.com',
      }
    : null

if (databaseUrl && !jwtSecret) {
  console.error('JWT_SECRET is required when DATABASE_URL is set (auth endpoints need it)')
  process.exit(1)
}
if (!databaseUrl) {
  console.warn(`[${factionSlug}] DATABASE_URL not set — serving /api/health only`)
}

// One pool for the API, scrapers, and ticker. The error handler matters: an
// idle-client error on an unhandled pg.Pool 'error' event kills the process
// (which shows up as an nginx 502 crash-loop).
const db = databaseUrl ? new pg.Pool({ connectionString: databaseUrl }) : undefined
db?.on('error', (err) => console.error(`[${factionSlug}] pg pool error:`, err.message))

// #609: read-only connection to the shared `global` database. Entirely
// optional — a tenant without it behaves exactly as it did before the control
// plane existed, which is the guarantee the whole design rests on.
//
// ⚠️ Small pool, and it must stay small. This is a low-traffic path (fleet
// metadata, and later the OC model and item prices) shared by every tenant
// against ONE database. Sizing it like the primary pool would let five tenants
// exhaust global's connection slots between them and take down the thing they
// all read — the opposite of the isolation this is supposed to provide.
const globalDatabaseUrl = process.env.GLOBAL_DATABASE_URL
const globalDb = globalDatabaseUrl
  ? new pg.Pool({ connectionString: globalDatabaseUrl, max: 2 })
  : undefined
// Logged, never fatal: an unreachable control plane is an expected state.
globalDb?.on('error', (err) => console.error(`[${factionSlug}] global pg pool error:`, err.message))
if (!globalDatabaseUrl) console.warn(`[${factionSlug}] GLOBAL_DATABASE_URL not set — control-plane reads disabled`)

// Readiness flags (#76): flipped true below once background work is armed, so
// /api/health/ready reports the real per-faction state to the uptime monitor.
const health = { scheduler: false, ticker: false }

const app = await buildServer({
  factionSlug,
  db,
  globalDb,
  // ⚠️ #632: this tenant's OWN token, never the fleet secret.
  //
  // An earlier version passed FLEET_METRICS_SECRET here and derived the token
  // in-process, which put the fleet secret in every tenant's environment — so a
  // leak from any one faction would have read every faction's metrics, the
  // exact failure the derivation exists to prevent. Only the admin container
  // holds the secret; a tenant holds a value that says nothing about any other.
  //
  // Generated by db/new-faction.mjs, or printed for an existing faction by
  // db/fleet-metrics-token.mjs. Absent leaves the endpoint unregistered.
  fleetMetricsToken: process.env.FLEET_METRICS_TOKEN || undefined,
  // ⚠️ #782: a SEPARATE token from FLEET_METRICS_TOKEN, derived from the same
  // fleet secret but scoped ("chain-watch:<slug>"). The Discord bot holds this
  // one; handing it the metrics token would give it key-pool depth for free.
  // Printed by db/chain-watch-token.mjs. Absent leaves the endpoint unregistered.
  chainWatchToken: process.env.CHAIN_WATCH_TOKEN || undefined,
  warOverviewToken: process.env.WAR_OVERVIEW_TOKEN || undefined,
  tornBaseUrl,
  jwtSecret,
  keyEncryptionKey,
  health,
  // Spy-stat providers for the war room (#100) — optional, operator-level.
  tornStatsApiKey: process.env.TORNSTATS_API_KEY || undefined,
  bspApiKey: process.env.BSP_API_KEY || undefined,
  // Web Push (#207) — optional; push is disabled until the operator sets it.
  vapid,
  // In-app feedback → GitHub issue (#253) — optional; disabled without a PAT.
  feedbackGithubToken: process.env.FEEDBACK_GITHUB_TOKEN || undefined,
  feedbackGithubRepo: process.env.FEEDBACK_GITHUB_REPO || 'DobrowneyT/torn-dashboard',
  feedbackLabel: process.env.FEEDBACK_LABEL || 'needs-triage',
  // Public origin so feedback attachment URLs embed correctly in GitHub issues.
  publicBaseUrl: process.env.PUBLIC_BASE_URL || undefined,
})
if (vapid) console.log(`[${factionSlug}] Web Push armed (VAPID configured)`)
await app.listen({ port, host: '0.0.0.0' })
console.log(`[${factionSlug}] API listening on :${port}`)

// In-process scrapers (slice #67+): armed whenever the key-at-rest secret
// is present. Every job registers DISABLED — per-job enablement (and
// cadence) is the faction admin's bring-up step in Global Admin, so an
// armed-but-unconfigured faction costs gate-checks and zero Torn calls.
// A failure here (e.g. a faction DB that hasn't had db/migrate.mjs run
// yet) degrades to dashboards-only — it must never crash-loop the API.
if (db) {
  if (!keyEncryptionKey) {
    console.warn(`[${factionSlug}] KEY_ENCRYPTION_KEY not set — scrapers and war-room ticker NOT armed`)
  } else {
    try {
      const { startScrapers } = await import('./scraper/registerJobs.js')
      await startScrapers({
        db, tornBaseUrl, encryptionKey: keyEncryptionKey,
        // The one resolver built in buildServer — shared so an admin flag
        // write invalidates the same cache the scheduler reads (#609 slice 5).
        flags: app.flagResolver,
        // The fleet item catalogue fast path (#609 slice 7). items-sync adopts
        // it while it is fresh and falls back to this faction's pool otherwise.
        globalDb,
        // #139: lets war-lifecycle auto-fetch spies on the weekly setup.
        tornStatsApiKey: process.env.TORNSTATS_API_KEY || undefined,
        bspApiKey: process.env.BSP_API_KEY || undefined,
      })
      health.scheduler = true
      console.log(`[${factionSlug}] scrapers scheduled`)

      // Re-arm competition boundary timers (#230): any competition whose start
      // or end is still in the future gets its one-off capture timer back after
      // a restart.
      await app.competitionTimers?.rearmAll()

      // War-room ticker (slice #71): runs at 1 Hz but self-gates each tick on
      // war_room_config_v2.enabled + the managed war's active window, so an
      // idle faction costs one SELECT per second and zero Torn calls.
      if (app.warRoomHub) {
        const { createWarRoomTicker } = await import('./warRoomTicker.js')
        const { createKeyPool } = await import('./scraper/keyPool.js')
        const ticker = createWarRoomTicker({
          db,
          pool: createKeyPool({ db, encryptionKey: keyEncryptionKey }),
          hub: app.warRoomHub,
          tornBaseUrl,
          // Surge fan-out (#208) sends background web-push via the #207 service.
          pushService: app.pushService,
        })
        ticker.start()
        health.ticker = true
        console.log(`[${factionSlug}] war-room ticker armed (config-gated)`)
      }
    } catch (err) {
      console.error(
        `[${factionSlug}] scraper startup failed — API continues without scrapers. ` +
        `If this DB predates the scraper slices, run: node db/migrate.mjs`,
        err
      )
    }
  }

  // #255: daily prune of feedback attachments — delete stored files once their
  // linked GitHub issue is closed, plus a hard TTL fallback. Only when feedback
  // is configured.
  if (db && process.env.FEEDBACK_GITHUB_TOKEN) {
    const pruneDb = db
    const { pruneFeedbackAttachments } = await import('./feedback.js')
    const runPrune = () =>
      pruneFeedbackAttachments({
        db: pruneDb,
        githubToken: process.env.FEEDBACK_GITHUB_TOKEN!,
        githubRepo: process.env.FEEDBACK_GITHUB_REPO || 'DobrowneyT/torn-dashboard',
      })
        .then((r) => {
          if (r.closedAttachmentsDeleted || r.ttlDeleted) {
            console.log(
              `[${factionSlug}] feedback prune: removed ${r.closedAttachmentsDeleted} closed-issue + ` +
              `${r.ttlDeleted} over-TTL attachment(s) (${r.errors} issue-check error(s))`
            )
          }
        })
        .catch((err) => console.error(`[${factionSlug}] feedback prune failed:`, err))
    const pruneTimer = setInterval(runPrune, 24 * 60 * 60 * 1000)
    pruneTimer.unref?.()
    void runPrune() // once at startup
  }

  // #528 Part 2: daily hard-prune of enemy loadout observations past their
  // retention window. Unconditional (no operator opt-in), unlike the
  // scraper-job table's registered-DISABLED default (scraper/scheduler.ts) —
  // this is real intel about individual players, so the retention promise
  // in warRoomLoadout.ts must hold from the moment the feature is live, not
  // from whenever someone remembers to flip a switch in Global Admin.
  if (db) {
    const pruneDb = db
    const runLoadoutPrune = () =>
      import('./warRoomLoadout.js')
        .then(({ pruneLoadoutObservations }) => pruneLoadoutObservations(pruneDb))
        .then((r) => {
          if (r.pruned) {
            console.log(`[${factionSlug}] loadout prune: removed ${r.pruned} observation(s) past ${r.retentionDays}d`)
          }
        })
        .catch((err) => console.error(`[${factionSlug}] loadout prune failed:`, err))
    const loadoutPruneTimer = setInterval(runLoadoutPrune, 24 * 60 * 60 * 1000)
    loadoutPruneTimer.unref?.()
    void runLoadoutPrune() // once at startup
  }
}
