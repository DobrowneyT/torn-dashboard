/**
 * In-place edits to `deploy/docker-compose.override.yml` for fleet-metrics
 * tokens (#632).
 *
 * ⚠️ **Why a file rewriter and not just a printout.** `db/new-faction.mjs`
 * bakes a tenant's token in at provisioning time, which covers every faction
 * created AFTER the operator sets `FLEET_METRICS_SECRET`. It does nothing for
 * the ones that already exist — and that is the normal case, because the
 * secret is generated once, later, against a fleet that is already running.
 * Measured on the live box: five tenants, all provisioned before the secret
 * was set. Leaving that as a hand-paste is how one tenant ends up with a stale
 * token and reports `metricsError` forever while the other four look fine.
 *
 * ⚠️ Rotating the secret changes EVERY token at once, so this rewrites all of
 * them in one pass. A partial rotation is the worst state: the admin container
 * derives from the new secret, so every tenant still holding an old token
 * 401s, and the status page reports "not measured" — which #645 proved reads
 * as healthy to a human.
 *
 * Kept separate from the CLI so it can be tested without a deploy directory,
 * the same split `db/adminEnvFile.mjs` uses for `.env`.
 */

/** The comment new-faction.mjs writes above the value, reused on insert. */
const TOKEN_COMMENT = (slug) => [
  '      # ⚠️ THIS faction\'s own fleet-metrics token (#632), not the fleet secret.',
  '      # Putting FLEET_METRICS_SECRET in every tenant would mean a leak from any',
  '      # one faction reads every faction\'s metrics; the admin container holds the',
  '      # secret and derives what it needs. Regenerate with',
  `      # \`node db/fleet-metrics-token.mjs ${slug}\`.`,
]

/**
 * Set `FLEET_METRICS_TOKEN` on each `api-<slug>` service.
 *
 * Replaces the value where the key already exists, appends it to the service's
 * `environment:` block where it does not. Returns `{ text, updated, added,
 * missing }` — `missing` being slugs with no `api-<slug>` service in the file,
 * which the caller must not treat as success.
 *
 * ⚠️ Comments, ordering and unrelated services survive byte-for-byte. This
 * file is generated by appending, then hand-edited for years; a rewriter that
 * reformatted it would make every future diff unreadable and would be trusted
 * by nobody.
 */
export function setOverrideTokens(text, tokensBySlug) {
  const wanted = new Map(Object.entries(tokensBySlug))
  for (const [slug, token] of wanted) {
    // ⚠️ Hex only, and checked here rather than at the call site. Compose
    // interpolates `${...}` inside the compose file itself, so a value with a
    // `$` in it would be silently mangled into a token that never matches —
    // the same class of failure that truncated ADMIN_PASSWORD_HASH mid-string
    // and crash-looped the admin container.
    if (!/^[0-9a-f]{64}$/.test(token)) {
      throw new Error(`token for "${slug}" is not a 64-char hex HMAC digest`)
    }
  }

  const lines = text.split('\n')
  const out = []
  const updated = []
  const added = []

  let slug = null          // the api-<slug> service we are inside, if any
  let inEnv = false        // ...and inside its `environment:` block
  let wroteForService = false

  const flushInsert = (forSlug) => {
    out.push(...TOKEN_COMMENT(forSlug))
    out.push(`      FLEET_METRICS_TOKEN: ${wanted.get(forSlug)}`)
    added.push(forSlug)
  }

  for (const line of lines) {
    const service = /^ {2}([A-Za-z0-9_.-]+):\s*$/.exec(line)
    if (service) {
      // Leaving a service whose environment block never carried the key.
      if (slug && inEnv && !wroteForService && wanted.has(slug)) flushInsert(slug)
      const m = /^api-(.+)$/.exec(service[1])
      slug = m ? m[1] : null
      inEnv = false
      wroteForService = false
      out.push(line)
      continue
    }

    if (slug && /^ {4}environment:\s*$/.test(line)) {
      inEnv = true
      out.push(line)
      continue
    }

    // The environment block ends at the first non-blank line indented 4 or
    // less — `depends_on:`, `restart:`, or the next service.
    if (inEnv && line.trim() !== '' && /^ {0,4}\S/.test(line)) {
      if (!wroteForService && wanted.has(slug)) flushInsert(slug)
      inEnv = false
      out.push(line)
      continue
    }

    if (inEnv && wanted.has(slug) && /^ {6}FLEET_METRICS_TOKEN:/.test(line)) {
      out.push(`      FLEET_METRICS_TOKEN: ${wanted.get(slug)}`)
      wroteForService = true
      updated.push(slug)
      continue
    }

    out.push(line)
  }

  // The file ended while still inside a service's environment block.
  if (slug && inEnv && !wroteForService && wanted.has(slug)) {
    // ⚠️ Insert BEFORE any trailing blank lines, or the key lands outside the
    // block it belongs to and compose reads it as a sibling of `services:`.
    let tail = out.length
    while (tail > 0 && out[tail - 1].trim() === '') tail -= 1
    const trailing = out.splice(tail)
    flushInsert(slug)
    out.push(...trailing)
  }

  const touched = new Set([...updated, ...added])
  const missing = [...wanted.keys()].filter((s) => !touched.has(s))
  return { text: out.join('\n'), updated, added, missing }
}
