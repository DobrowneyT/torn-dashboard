/**
 * The bonus-percentage rule exists TWICE and this is what stops it drifting.
 *
 * ⚠️ The duplication is forced: `tnl-war-room-dibs.user.js` is a single file
 * injected into Torn by Tampermonkey and cannot import from the app, while the
 * display needs the same rule to derive a percentage from the descriptions of
 * the 1,301 observations captured before the field existed. So the rule is
 * written in both places and asserted identical here, over every description
 * SHAPE seen in production.
 *
 * This repo has watched one idea drift across two implementations more than
 * once — LOSS_RESULTS in two files, WIN_RESULTS disagreeing about `Special` —
 * and the fix both times was a test like this one.
 */
import { describe, expect, it } from 'vitest'
import { readFileSync } from 'node:fs'
import { bonusPercentFromDescription } from '../warRoomLoadout'

/** Lift `bonusPercent` out of the userscript and run it directly. */
function userscriptParse() {
  const src = readFileSync(
    new URL('../../../userscripts/tnl-war-room-dibs.user.js', import.meta.url), 'utf8'
  )
  const i = src.indexOf('function bonusPercent(')
  expect(i, 'bonusPercent not found in the userscript').toBeGreaterThan(-1)
  let depth = 0
  let end = -1
  for (let j = src.indexOf('{', i); j < src.length; j++) {
    if (src[j] === '{') depth++
    else if (src[j] === '}') { depth--; if (depth === 0) { end = j; break } }
  }
  // eslint-disable-next-line no-new-func
  return new Function(`${src.slice(i, end + 1)}; return bonusPercent`)()
}

/**
 * ⚠️ Every one of these is a REAL description, taken from the 1,301 forge
 * captures on 2026-10-09 — not invented shapes. The counts in the comments are
 * how often each appeared, which is why the negative-percentage cases are not
 * edge cases worth skipping.
 */
const PRODUCTION_DESCRIPTIONS = [
  // Leading percentage — the common case.
  ['+4% critical hit rate', 4],                                   // ×368
  ['+5% critical hit rate', 5],                                   // ×341
  ['+30% ammo per mag', 30],                                      // ×130
  ['+25% ammo conservation', 25],                                 // ×115
  ['11% chance of restoring energy used upon final hit', 11],     // ×78
  ['17% chance to Motivate self increasing all stats by 10% (x5)', 17], // ×55
  ['+6% damage', 6],                                              // ×48

  // ⚠️ Mid-string and POSITIVE — the specials that matter, all missed by the
  // first anchored-to-start version of this rule.
  ['Eviscerates opponent causing them 15% extra damage on further hits', 15], // ×75
  ['Ignores 26% of armor mitigation', 26],                        // ×32  Penetrate
  ['Life regenerated by 10% of damage dealt', 10],                // ×17  Bloodlust
  ["Instantly defeats a target if they're below 15% life", 15],   // ×16  Execute

  // ⚠️ Mid-string and NEGATIVE — penalties. Reporting these would advertise a
  // drawback as a benefit.
  ['+1.75 Accuracy -30% Dexterity', null],                        // ×45
  ['+2.00 Accuracy -30% Dexterity', null],                        // ×17
  ['+4 stealth, -5% damage', null],                               // ×14
  ['+3 stealth, -5% damage', null],                               // ×13

  // No percentage at all.
  ['+1.50 Accuracy', null],                                       // ×237
  ['-5.00 Opp Acc -3 Opp stealth', null],                         // ×141
  ['+2 extra magazines', null],                                   // ×98
  ['+5.00 Accuracy on first turn', null],                         // ×96
  ["Disables an opponent's weapon upon a hand or arm hit for 3 turns", null], // ×71
  ['+1.50 Accuracy -3 stealth', null],                            // ×56

  // From MonChoon's 2026-10-09 captures.
  ['16% increased hit chance for every miss', 16],
  ['37% chance to Burn opponent causing 90% damage over 3 turns', 37],
  ['84% increased Heart damage', 84],
  ['+1.00 Accuracy', null],

  // Shapes neither source should mishandle.
  ['', null],
  ['2.5% chance of something', 2.5],
]

describe('bonus percentage: the two implementations agree', () => {
  const fromUserscript = userscriptParse()

  for (const [description, expected] of PRODUCTION_DESCRIPTIONS) {
    it(`${JSON.stringify(description).slice(0, 56)} → ${expected}`, () => {
      expect(bonusPercentFromDescription(description), 'frontend').toBe(expected)
      expect(fromUserscript(description), 'userscript').toBe(expected)
    })
  }

  it('agrees on null and undefined', () => {
    for (const v of [null, undefined]) {
      expect(bonusPercentFromDescription(v)).toBe(null)
      expect(fromUserscript(v)).toBe(null)
    }
  })

  /**
   * ⚠️ The rule in one sentence, asserted rather than only described: the first
   * percentage that is not a penalty. Both halves matter — "first" (not
   * largest) and "not a penalty" (not simply first).
   */
  it('takes the first non-negative percentage, not the largest and not a penalty', () => {
    for (const fn of [bonusPercentFromDescription, fromUserscript]) {
      expect(fn('10% chance to do 99% damage')).toBe(10)
      expect(fn('-99% something then 10% else')).toBe(10)
      expect(fn('-99% only')).toBe(null)
    }
  })
})
