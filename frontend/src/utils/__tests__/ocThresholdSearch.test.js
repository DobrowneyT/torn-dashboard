// #692 — the threshold search: the minimum CPR we actually publish.
//
// Descends from slice 3's ceiling looking for the vector that maximises
// $ per faction member per day, bounded below by the scope break-even.
//
// ⚠️ Every candidate costs a call to tornprobability, so the search is
// evaluation-budgeted by construction. Most of these tests count the calls.
import { describe, expect, it, vi } from 'vitest'
import { candidateVectors, searchThresholds } from '../ocThresholdSearch'

const roster = (vals) => vals.map((cpr, i) => ({ member_id: `m${i}`, cpr }))
const P3 = ['P1', 'P2', 'P3']

/** Independent pools per role, deep enough to seat several crews. */
const deepRoster = (n = 3, depth = 12) =>
  Object.fromEntries(
    Array.from({ length: n }, (_, r) => [
      `P${r + 1}`,
      Array.from({ length: depth }, (_, i) => ({ member_id: `r${r}m${i}`, cpr: 95 - i })),
    ])
  )

/** A probe that always succeeds well and pays a fixed amount. */
const flatProbe = (expectedValue = 100, successChance = 0.95) =>
  vi.fn(async () => ({ expectedValue, successChance }))

describe('candidateVectors', () => {
  it('⚠️ produces ONE vector per achievable crew count, not one per CPR combination', () => {
    // The whole reason the search is affordable. A grid over six roles is
    // millions of probability calls; this is a handful.
    const readings = deepRoster(3, 12)
    const cands = candidateVectors(readings, P3)
    expect(cands.length).toBeLessThanOrEqual(4)
    expect(cands.map((c) => c.crews)).toEqual([...cands.map((c) => c.crews)].sort((a, b) => a - b))
    expect(new Set(cands.map((c) => c.crews)).size).toBe(cands.length)
  })

  it('⚠️ every candidate actually seats the crews it claims', () => {
    // Generated by a Hall-safe rule then greedily raised — if the raising step
    // overshoots, the vector is a lie and every score built on it is wrong.
    const readings = deepRoster(3, 12)
    for (const c of candidateVectors(readings, P3)) {
      expect(c.verifiedCrews).toBeGreaterThanOrEqual(c.crews)
    }
  })

  it('its k=1 candidate is at least as high as slice 3’s ceiling', () => {
    // Slice 3 IS the k=1 case of the same Hall argument, so the search must not
    // start below the ceiling it was told to descend from.
    const readings = deepRoster(3, 12)
    const one = candidateVectors(readings, P3).find((c) => c.crews === 1)
    for (const p of P3) expect(one.vector[p]).toBeGreaterThanOrEqual(93)
  })

  it('returns nothing when no crew can be fielded at all', () => {
    const readings = { P1: roster([90]), P2: roster([90]), P3: roster([90]) }
    // Three roles, one member each — but they are different members, so one
    // crew IS fieldable. Now take a role away entirely:
    expect(candidateVectors({ ...readings, P3: [] }, P3)).toEqual([])
  })
})

describe('searchThresholds', () => {
  const base = {
    positionIds: P3,
    rosterSize: 60,
    category: { scopeCost: 4, scopeReward: 5 },   // break-even 80%
    gap: 0.5,
  }

  it('⚠️ spends one probability call per candidate, not per vector', async () => {
    const probe = flatProbe()
    const out = await searchThresholds({ ...base, readings: deepRoster(3, 12), probe })
    expect(probe.mock.calls.length).toBe(out.evaluated.length)
    expect(probe.mock.calls.length).toBeLessThanOrEqual(6)
  })

  it('prefers more crews when E(X) holds up', async () => {
    // Same payout whatever the crew: more crews is strictly more income.
    const out = await searchThresholds({ ...base, readings: deepRoster(3, 12), probe: flatProbe() })
    expect(out.chosen.crews).toBe(Math.max(...out.evaluated.map((e) => e.crews)))
  })

  it('⚠️ prefers fewer, stronger crews when the payout falls away fast enough', async () => {
    // The interior optimum the whole design turns on. The candidate set here is
    // {95}/{94}/{93}/{92} seating 1/2/3/4 crews, so whether more crews wins
    // depends entirely on how steeply E(X) decays:
    //
    //   E(X) = (avg-80)^4  →  k=3 wins (8.57e4 against 5.06e4)
    //   E(X) = 3^(avg-80)  →  k=1 wins (1.43e7 against 4.78e6)
    //
    // Both are correct answers to different crimes, which is the point — the
    // optimum is interior and neither endpoint is right a priori.
    const probe = vi.fn(async (vector) => {
      const avg = Object.values(vector).reduce((a, b) => a + b, 0) / Object.keys(vector).length
      return { expectedValue: Math.pow(3, avg - 80), successChance: 0.95 }
    })
    const out = await searchThresholds({ ...base, readings: deepRoster(3, 12), probe })
    expect(out.chosen.crews).toBe(1)
  })

  it('⚠️ prefers more, weaker crews when the payout decays gently', async () => {
    // The same roster and the same code, opposite answer. A search hardwired to
    // either endpoint would be wrong half the time.
    const probe = vi.fn(async (vector) => {
      const avg = Object.values(vector).reduce((a, b) => a + b, 0) / Object.keys(vector).length
      return { expectedValue: Math.pow(avg - 80, 4), successChance: 0.95 }
    })
    const out = await searchThresholds({ ...base, readings: deepRoster(3, 12), probe })
    expect(out.chosen.crews).toBe(3)
  })

  it('⚠️ takes a scope-NEGATIVE crime when it pays, and flags it', async () => {
    // MonChoon, 2026-09-12: "I am okay to have the higher paying crimes scope
    // negative in the hopes that some lower ones balance it out (since we cant
    // control spawning)." Scope is fungible across the mix and cheaply topped
    // up by easier crimes, so refusing a lucrative crime because that ONE crime
    // is scope-negative optimises a sub-problem nobody has. Solvency across the
    // portfolio is #693's job.
    const probe = vi.fn(async (vector) => {
      const avg = Object.values(vector).reduce((a, b) => a + b, 0) / Object.keys(vector).length
      // Candidates average 95/94/93/92: the weak crews pay a fortune and fail
      // far too often to pay their scope back.
      return avg < 94 ? { expectedValue: 1e12, successChance: 0.5 } : { expectedValue: 1, successChance: 0.95 }
    })
    const out = await searchThresholds({ ...base, readings: deepRoster(3, 12), probe })
    expect(out.chosen.successChance).toBe(0.5)
    expect(out.chosen.aboveBreakEven).toBe(false)
    expect(out.chosen.netScope).toBeCloseTo(0.5 * 5 - 4, 6)   // -1.5 scope a spawn
    // Reported, not refused — nothing is rejected for scope.
    expect(out.rejected.some((r) => r.reason === 'below-break-even')).toBe(false)
  })

  it('reports net scope per candidate so the portfolio view has something to add up', async () => {
    const out = await searchThresholds({ ...base, readings: deepRoster(3, 12), probe: flatProbe(100, 0.9) })
    for (const e of out.evaluated) {
      expect(e.netScope).toBeCloseTo(0.9 * 5 - 4, 6)
      expect(e.aboveBreakEven).toBe(true)
    }
  })

  it('⚠️ rejects only a candidate it cannot price', async () => {
    // The one remaining rejection. Unpriceable is "unmeasured", not "worthless".
    const probe = vi.fn(async () => ({ expectedValue: null, successChance: 0.95 }))
    const out = await searchThresholds({ ...base, readings: deepRoster(3, 12), probe })
    expect(out.chosen).toBeNull()
    expect(out.reason).toBe('no-expected-value')
    expect(out.rejected.every((r) => r.reason === 'no-expected-value')).toBe(true)
  })

  it('⚠️ derives break-even from the category, never a hardcoded ladder', async () => {
    // A tier added above Elaborate must be a config entry, not a code change.
    const probe = flatProbe(100, 0.82)
    const advanced = await searchThresholds({ ...base, readings: deepRoster(3, 12), probe })
    const elaborate = await searchThresholds({
      ...base, readings: deepRoster(3, 12), probe, category: { scopeCost: 5, scopeReward: 6 },
    })
    const hypothetical = await searchThresholds({
      ...base, readings: deepRoster(3, 12), probe, category: { scopeCost: 9, scopeReward: 10 },
    })
    expect(advanced.breakEven).toBeCloseTo(0.8, 6)
    expect(elaborate.breakEven).toBeCloseTo(5 / 6, 6)
    expect(hypothetical.breakEven).toBeCloseTo(0.9, 6)
    // 82% clears Advanced and misses the other two — reported per candidate,
    // and a crime is still chosen in all three cases.
    expect(advanced.chosen.aboveBreakEven).toBe(true)
    expect(elaborate.chosen.aboveBreakEven).toBe(false)
    expect(hypothetical.chosen.aboveBreakEven).toBe(false)
    expect(elaborate.chosen).not.toBeNull()
  })

  it('⚠️ warm-starts from the incumbent but is NOT anchored to it', async () => {
    // The incumbent is a seed, not a tiebreak. If the roster degraded, the
    // published bar is now impossible and must fall — a margin that kept it
    // would publish a target nobody can hit.
    const readings = deepRoster(3, 12)
    const incumbent = { P1: 99, P2: 99, P3: 99 }   // nobody clears this any more
    const out = await searchThresholds({ ...base, readings, probe: flatProbe(), incumbent })
    expect(out.chosen).not.toBeNull()
    for (const p of P3) expect(out.chosen.vector[p]).toBeLessThan(99)
    expect(out.movedFrom).toEqual(incumbent)
  })

  it('explains why a threshold moved', async () => {
    const readings = deepRoster(3, 12)
    const out = await searchThresholds({
      ...base, readings, probe: flatProbe(), incumbent: { P1: 99, P2: 99, P3: 99 },
    })
    expect(out.movement).toBeTruthy()
    expect(out.movement.P1.from).toBe(99)
    expect(out.movement.P1.to).toBe(out.chosen.vector.P1)
  })

  it('⚠️ surfaces a near-tie rather than presenting an arbitrary pick as decided', async () => {
    const probe = vi.fn(async (vector) => {
      const avg = Object.values(vector).reduce((a, b) => a + b, 0) / Object.keys(vector).length
      // Tuned so two candidates score within a whisker of each other.
      return { expectedValue: 1000 / avg, successChance: 0.95 }
    })
    const out = await searchThresholds({ ...base, readings: deepRoster(3, 12), probe })
    expect(out.runnersUp.length).toBeGreaterThan(0)
    expect(typeof out.nearTie).toBe('boolean')
  })

  it('reports absent, not zero, when nothing can be computed', async () => {
    const out = await searchThresholds({ ...base, readings: {}, probe: flatProbe() })
    expect(out.chosen).toBeNull()
    expect(out.evaluated).toEqual([])
    expect(out.reason).toBe('no-crewable-vector')
  })
})

// ⚠️ Role priority, and the carry trade.
//
// The source document asks for the carry trade:
//
//   > If we can drop a role to a full carry, like Thief 1 / Picklock 2 then
//   > prioritise doing that and make the other roles a couple points higher.
//
// Building it turned up something more important: the greedy raise was already
// sacrificing a role — the roles share a member pool, so whoever is raised
// first takes the strongest members and whoever is raised last gets leftovers.
// It sorted by POSITION ID, so the starved role was whichever sorted last. On a
// six-role crime that is P6, chosen for no reason at all.
describe('role priority and the carry trade', () => {
  const P4 = ['P1', 'P2', 'P3', 'P4']
  // P4 is the carry: almost no impact on success. Note P3 outranks P2.
  const WEIGHTS = { P1: 34.6, P2: 30.0, P3: 32.5, P4: 2.9 }

  /**
   * ⚠️ ONE shared pool across all four roles — the realistic shape, and the only
   * one where priority means anything. With a separate pool per role nobody
   * competes and the order is irrelevant. My first fixture made that mistake.
   */
  const shared = () => {
    const pool = Array.from({ length: 12 }, (_, i) => ({ member_id: `m${i}`, cpr: 95 - i }))
    return Object.fromEntries(P4.map((p) => [p, pool.map((r) => ({ ...r }))]))
  }

  it('⚠️ gives the strongest members to the HIGHEST-WEIGHT role, not to P1', () => {
    const byWeight = candidateVectors(shared(), P4, { weights: WEIGHTS })[0].vector
    // 34.6% > 32.5% > 30.0% > 2.9%  →  P1 > P3 > P2 > P4
    expect(byWeight.P1).toBeGreaterThan(byWeight.P3)
    expect(byWeight.P3).toBeGreaterThan(byWeight.P2)
    expect(byWeight.P2).toBeGreaterThan(byWeight.P4)
  })

  it('⚠️ starves a DIFFERENT role when the weights say so', () => {
    // Same roster, weights reversed: the sacrifice must follow the weights.
    const reversed = { P1: 2.9, P2: 30.0, P3: 32.5, P4: 34.6 }
    const v = candidateVectors(shared(), P4, { weights: reversed })[0].vector
    expect(v.P4).toBeGreaterThan(v.P3)
    expect(v.P3).toBeGreaterThan(v.P2)
    expect(v.P2).toBeGreaterThan(v.P1)
  })

  it('falls back to a stable order when weights are absent', () => {
    const a = candidateVectors(shared(), P4)
    const b = candidateVectors(shared(), P4)
    expect(a).toEqual(b)
    expect(a.every((c) => !c.carryRole)).toBe(true)
  })

  it('⚠️ does NOT spend a probability call on a carry vector that can only lose', () => {
    // E(X) is monotone in CPR, so a vector that merely lowers the carry role
    // and lifts nothing scores strictly worse. Generating it would double the
    // call budget to evaluate candidates we already know lose.
    const cands = candidateVectors(shared(), P4, { weights: WEIGHTS })
    for (const c of cands.filter((x) => x.carryRole)) {
      const flat = cands.find((f) => !f.carryRole && f.crews === c.crews)
      expect(P4.some((p) => p !== c.carryRole && c.vector[p] > flat.vector[p])).toBe(true)
    }
  })

  it('every candidate still seats the crews it claims', () => {
    for (const c of candidateVectors(shared(), P4, { weights: WEIGHTS })) {
      expect(c.verifiedCrews).toBeGreaterThanOrEqual(c.crews)
    }
  })

  it('stays budgeted — at most two vectors per crew count', () => {
    const byCrews = {}
    for (const c of candidateVectors(shared(), P4, { weights: WEIGHTS })) {
      byCrews[c.crews] = (byCrews[c.crews] ?? 0) + 1
    }
    for (const n of Object.values(byCrews)) expect(n).toBeLessThanOrEqual(2)
  })

  it('picks the carry role by weight, never by position order', () => {
    const weights = { P1: 2.1, P2: 34.6, P3: 30.0, P4: 33.3 }
    const cands = candidateVectors(shared(), P4, { weights })
    expect(cands.filter((c) => c.carryRole).every((c) => c.carryRole === 'P1')).toBe(true)
  })

  it('threads weights through the search', async () => {
    const probe = vi.fn(async () => ({ expectedValue: 100, successChance: 0.95 }))
    const out = await searchThresholds({
      readings: shared(), positionIds: P4, rosterSize: 60,
      category: { scopeCost: 4, scopeReward: 5 }, gap: 0.5, weights: WEIGHTS, probe,
    })
    expect(out.chosen).not.toBeNull()
    expect(out.chosen.vector.P1).toBeGreaterThan(out.chosen.vector.P4)
  })
})
